def flatten(measures: dict):
    out = []
    for m in sorted(measures):
        out.extend(measures[m])
    return out


def fmt(events):
    joiner = chr(10)
    return joiner.join(f"{k} {d:g}" for k, d in events) + joiner


def merge_adjacent(events):
    out = []
    for key, beats in events:
        if out and out[-1][0] == key and key != "p":
            out[-1] = (key, out[-1][1] + beats)
        else:
            out.append((key, beats))
    return out


