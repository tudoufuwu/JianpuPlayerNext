def close(measures: dict, expected: float, label: str) -> None:
    bad = []
    for m, events in sorted(measures.items()):
        total = sum(d for _, d in events)
        if abs(total - expected) > 1e-9:
            bad.append(f"m{m}={total:g}")
    if bad:
        raise AssertionError(f"{label} 不闭合({expected}拍): {', '.join(bad)}")
    print(f"{label}: {len(measures)} 小节全部闭合 {expected:g} 拍 ✓")


def merge_adjacent(events):
    """流级合并同键相邻事件(延音线); 例外: m33|m34 边界的 h2.5|h2.0 是两次独立攻击。"""
    out = []
    for key, beats in events:
        if out and out[-1][0] == key and key != "p" and not (key == "h" and abs(out[-1][1] - 2.5) < 1e-9):
            out[-1] = (key, out[-1][1] + beats)
        else:
            out.append((key, beats))
    return out


